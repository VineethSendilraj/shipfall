// Dev tool: generates src/demo-script.js by letting an autopilot play the seeded showcase,
// then replays the hard-coded script and verifies the outcome is identical.
// Usage: node scripts/author-demo.mjs [--check]
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createDemoRunner, scriptedInput, DEMO } from '../src/demo.js';
import { ARM_MIN, ARM_MAX, CLOSE_TIME, PX_PER_M } from '../src/sim.js';

const KEYS = ['left', 'right', 'up', 'down'];
const clamp = (v, lo, hi) => Math.max(lo, Math.min(hi, v));

// Per-round choreography for the autopilot.
const STYLE = {
  1: { armStartAlt: 150, armOffset: 6, closeDy: -5, latGain: 1.8 },
  2: { armStartAlt: 120, armOffset: 2, closeDy: 0, latGain: 2.2, lazyFrom: 2.2, lazyUntilDx: 17 },
  3: { armStartAlt: 140, armOffset: 2, closeDy: 0, latGain: 2.2 },
};

function makeAutopilot() {
  const engaged = {};
  return (frame, game) => {
    const inp = { left: false, right: false, up: false, down: false, close: false };
    if (game.phase !== 'live') return inp;
    const b = game.activeBooster();
    if (!b) return inp;
    const tw = game.towers[b.tower];
    const st = STYLE[game.round] || STYLE[3];

    const target = clamp(b.zeroY + st.armOffset, ARM_MIN, ARM_MAX);
    const armsGo = b.state === 'waiting' || game.altitudeM(b) < st.armStartAlt;
    if (armsGo) {
      const diff = target - tw.armY;
      const coast = Math.abs(tw.armVel) / 16;
      const moving = Math.abs(tw.armVel) > 1;
      if (moving) {
        if (Math.sign(diff) === Math.sign(tw.armVel) && Math.abs(diff) > coast + 0.3) {
          if (diff > 0) inp.down = true;
          else inp.up = true;
        }
      } else if (diff > 3.5) inp.down = true;
      else if (diff < -3.5) inp.up = true;
    }
    if (b.state !== 'falling') return inp;

    const dx = b.x - tw.cx;
    if (process.env.DEBUG && frame % 10 === 0) {
      console.log(frame, `r${game.round} y=${b.y.toFixed(1)} arm=${tw.armY.toFixed(1)} dx=${dx.toFixed(1)} vx=${b.vx.toFixed(1)} vy=${(b.vy / PX_PER_M).toFixed(2)} fuel=${b.fuel.toFixed(0)} open=${tw.open}`);
    }
    let desired = clamp(-dx * st.latGain, -60, 60);
    if (st.lazyFrom !== undefined && game.roundT >= st.lazyFrom && !engaged[game.round]) {
      if (Math.abs(dx) > st.lazyUntilDx) engaged[game.round] = true;
      else desired = b.vx;
    }
    const err = b.vx - desired;
    if (err > 1.5) inp.left = true;
    else if (err < -1.5) inp.right = true;

    const predY = b.y + b.vy * CLOSE_TIME;
    const predDx = dx + b.vx * CLOSE_TIME;
    const dy = predY - tw.armY;
    const vy = b.vy / PX_PER_M;
    if (
      b.burning &&
      b.y >= b.zeroY - 2 &&
      dy >= st.closeDy - 0.8 &&
      dy <= st.closeDy + 3 &&
      Math.abs(predDx) < 2.5 &&
      Math.abs(b.vx) < 6 &&
      vy < 2.4 &&
      tw.open >= 1 &&
      !tw.closing &&
      Math.abs(tw.armVel) < 2
    ) {
      inp.close = true;
    }
    return inp;
  };
}

function run(inputFn, record) {
  const runner = createDemoRunner((frame, game) => {
    const inp = inputFn(frame, game);
    if (record) record.push(inp);
    return inp;
  });
  const log = [];
  let checksum = 0;
  let guard = 0;
  while (!runner.done && guard++ < 60 * 60) {
    runner.step();
    const g = runner.game;
    for (const e of g.events) {
      if (['catch', 'miss', 'crash', 'whiff', 'unlock', 'double', 'clang', 'gameover'].includes(e.type)) {
        log.push(`f${runner.frame} r${g.round} ${e.type}${e.perfect !== undefined ? (e.perfect ? ' PERFECT' : ' nice') : ''}${e.pts ? ' +' + e.pts : ''}${e.reason ? ' ' + e.reason : ''} score=${g.score}`);
      }
    }
    for (const b of g.boosters) checksum = (checksum * 31 + Math.round(b.x * 1000) + Math.round(b.y * 1000)) % 2147483647;
    checksum = (checksum * 31 + g.particles.length) % 2147483647;
  }
  return { runner, log, checksum };
}

function compress(frames) {
  const out = { left: [], right: [], up: [], down: [], close: [] };
  for (const k of KEYS) {
    let start = -1;
    frames.forEach((inp, f) => {
      if (inp[k] && start < 0) start = f;
      if (!inp[k] && start >= 0) {
        out[k].push([start, f]);
        start = -1;
      }
    });
    if (start >= 0) out[k].push([start, frames.length]);
  }
  frames.forEach((inp, f) => inp.close && out.close.push(f));
  return out;
}

const check = process.argv.includes('--check');
if (!check) {
  const frames = [];
  const a = run(makeAutopilot(), frames);
  console.log('autopilot run:\n  ' + a.log.join('\n  '));
  const script = compress(frames);
  const body = `// Generated by scripts/author-demo.mjs from a seeded autopilot run. Frame-keyed inputs: [start, end) holds.\nexport const DEMO_SCRIPT = ${JSON.stringify(script)};\n`;
  writeFileSync(fileURLToPath(new URL('../src/demo-script.js', import.meta.url)), body);
  const { DEMO_SCRIPT } = await import(`../src/demo-script.js?v=${Date.now()}`);
  const b = run(scriptedInput(DEMO_SCRIPT));
  console.log(`replay matches autopilot: ${a.checksum === b.checksum && a.runner.game.score === b.runner.game.score}`);
  report(b);
} else {
  report(run(scriptedInput()));
}

function report({ runner, log, checksum }) {
  const g = runner.game;
  console.log('scripted run:\n  ' + log.join('\n  '));
  console.log(`final score ${g.score}, stats ${JSON.stringify(g.stats)}, lives ${g.lives}`);
  console.log(`game over at frame ${runner.overAt}, done at frame ${runner.frame} = ${(runner.frame / 60).toFixed(2)} s (title ${DEMO.titleFrames}f, end ${DEMO.endFrames}f), checksum ${checksum}`);
}
